"""Generate flock_oui_table.h: the Wi-Fi prefixes the Flock engine watches.

Unlike the camera and drone tables this list is not "every OUI of a vendor":
Flock cameras use off-the-shelf radio modules, so most prefixes belong to the
module maker (Liteon, Espressif, Silicon Labs) and are shared with countless
other products. Each entry therefore names the vendor IEEE must have it
registered to, and the generator refuses to run if the registry disagrees.
That is what keeps phone and laptop prefixes out: an Apple, Samsung, ASUS and
Cisco Meraki prefix once sat in this list under other vendors' names.

Tiers:
  VENDOR  registered to a surveillance vendor itself; a match is a finding.
  CORE    module prefix field-reported in Flock cameras; corroboration needed.
  EXT     wider module set, only with the "extended OUI set" option on.

A locally administered prefix can never be a vendor's and is rejected; a
prefix missing from MA-L is allowed only where marked unregistered.

Usage:  python3 gen_flock_oui.py oui.csv > ../src/engines/flock_oui_table.h
Source: https://standards-oui.ieee.org/oui/oui.csv
"""
import csv, re, sys

LITEON = r'^Liteon Technology'
ESPRESSIF = r'^Espressif'
SILABS = r'^Silicon Laboratories'
UGSI = r'^Universal Global Scientific'
UNREG = None  # not in MA-L: kept from field reports, cannot collide with a vendor

ENTRIES = [
    # (prefix, tier, expected IEEE organisation)
    ('B41E52', 'VENDOR', r'^Flock Safety'),
    ('D411D6', 'VENDOR', r'^ShotSpotter'),

    ('00F48D', 'CORE', LITEON), ('145AFC', 'CORE', LITEON),
    ('24B2B9', 'CORE', LITEON), ('3C9180', 'CORE', LITEON),
    ('5800E3', 'CORE', LITEON), ('5C93A2', 'CORE', LITEON),
    ('646E69', 'CORE', LITEON), ('700894', 'CORE', LITEON),
    ('70C94E', 'CORE', LITEON), ('744CA1', 'CORE', LITEON),
    ('803049', 'CORE', LITEON), ('940853', 'CORE', LITEON),
    ('9C2F9D', 'CORE', LITEON), ('B81EA4', 'CORE', LITEON),
    ('C03532', 'CORE', LITEON), ('D03957', 'CORE', LITEON),
    ('D8F3BC', 'CORE', LITEON), ('E4AAEA', 'CORE', LITEON),
    ('E8D0FC', 'CORE', LITEON), ('F46ADD', 'CORE', LITEON),
    ('083A88', 'CORE', UGSI), ('E04F43', 'CORE', UGSI),
    ('588E81', 'CORE', SILABS), ('9035EA', 'CORE', SILABS),
    ('EC1BBD', 'CORE', SILABS),
    ('3C71BF', 'CORE', ESPRESSIF), ('A4CF12', 'CORE', ESPRESSIF),
    ('B83532', 'CORE', UNREG),

    # Atheros factory-default block: the camera's QCA9377 ships 00:03:7F MACs.
    ('00037F', 'EXT', r'^Atheros'),
    ('14B5CD', 'EXT', LITEON), ('E00AF6', 'EXT', LITEON),
    ('F8A2D6', 'EXT', LITEON),
    ('040D84', 'EXT', SILABS), ('1C34F1', 'EXT', SILABS),
    ('385B44', 'EXT', SILABS), ('943469', 'EXT', SILABS),
    ('B4E3F9', 'EXT', SILABS), ('F082C0', 'EXT', SILABS),
    ('A0C9A0', 'EXT', r'^Murata'),
    ('240AC4', 'EXT', ESPRESSIF), ('246F28', 'EXT', ESPRESSIF),
    ('2CF432', 'EXT', ESPRESSIF), ('30AEA4', 'EXT', ESPRESSIF),
    ('3C6105', 'EXT', ESPRESSIF), ('840D8E', 'EXT', ESPRESSIF),
    ('84F3EB', 'EXT', ESPRESSIF), ('8CAAB5', 'EXT', ESPRESSIF),
    ('98F4AB', 'EXT', ESPRESSIF), ('9C9C1F', 'EXT', ESPRESSIF),
    ('AC67B2', 'EXT', ESPRESSIF), ('BCDDC2', 'EXT', ESPRESSIF),
    ('C82B96', 'EXT', ESPRESSIF), ('CC50E3', 'EXT', ESPRESSIF),
    ('D8A01D', 'EXT', ESPRESSIF), ('DC5475', 'EXT', ESPRESSIF),
    ('EC6260', 'EXT', ESPRESSIF), ('F4CFA2', 'EXT', ESPRESSIF),
    ('FCF5C4', 'EXT', ESPRESSIF),
    ('606201', 'EXT', UNREG),
]


def main(path):
    reg = {}
    with open(path, newline='', encoding='utf-8', errors='replace') as fh:
        for rec in csv.DictReader(fh):
            if rec.get('Registry') == 'MA-L':
                reg[(rec.get('Assignment') or '').strip().upper()] = \
                    (rec.get('Organization Name') or '').strip()
    errors, rows, seen = [], [], set()
    for oui, tier, want in ENTRIES:
        if oui in seen:
            errors.append('%s listed twice' % oui)
        seen.add(oui)
        if int(oui[:2], 16) & 0x02:
            errors.append('%s is locally administered' % oui)
        org = reg.get(oui)
        if want is None:
            if org is not None:
                errors.append('%s is now registered to %s; review it' % (oui, org))
            org = 'not in the IEEE registry'
        elif org is None or not re.search(want, org, re.I):
            errors.append('%s is registered to %r, expected %s' % (oui, org, want))
        rows.append((oui, tier, org))
    if errors:
        sys.exit('\n'.join(errors))
    rows.sort()
    out = sys.stdout.write
    out('// SPDX-License-Identifier: MIT\n')
    out('// Generated by tools/gen_flock_oui.py, checked against the IEEE MA-L\n')
    out('// registry. Do not edit by hand; change the generator and re-run it.\n')
    for t in ('VENDOR', 'CORE', 'EXT'):
        out('// %-6s %d\n' % (t, sum(1 for r in rows if r[1] == t)))
    out('#pragma once\n#include <stdint.h>\n\n')
    out('#define FLOCK_OUI_EXT    1  // module prefix, extended set only\n')
    out('#define FLOCK_OUI_CORE   2  // module prefix seen in Flock cameras\n')
    out('#define FLOCK_OUI_VENDOR 3  // registered to a surveillance vendor\n\n')
    out('struct FlockOui { uint8_t b[3]; uint8_t tier; };\n\n')
    out('// Sorted, so entries sharing a first byte are contiguous.\n')
    out('static const FlockOui FLOCK_OUI_TABLE[] = {\n')
    for oui, tier, org in rows:
        b = [int(oui[i:i + 2], 16) for i in (0, 2, 4)]
        out('    { {0x%02x,0x%02x,0x%02x}, FLOCK_OUI_%-6s }, // %s\n'
            % (b[0], b[1], b[2], tier, org))
    out('};\n')
    out('static const int FLOCK_OUI_COUNT =\n'
        '    sizeof(FLOCK_OUI_TABLE) / sizeof(FLOCK_OUI_TABLE[0]);\n')


if __name__ == '__main__':
    main(sys.argv[1])
