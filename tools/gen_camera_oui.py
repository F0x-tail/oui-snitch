#!/usr/bin/env python3
"""Generate camera_oui.h from the IEEE MA-L registry.

Mirrors the Flock engine's table/bucket layout so the camera matcher can reuse
the same O(bucket) ISR-safe lookup.

  ext = 0  camera-vendor OUI (registered to a camera manufacturer) -> always matched
  ext = 1  "extended" entry, only matched when the extended toggle is on.
           Reserved for *observed* Wi-Fi module OUIs (Espressif/Realtek/Tuya
           etc.) that specific cameras are built on. Deliberately EMPTY by
           default: blanket-listing a module vendor would match every device
           built on that module, not just cameras.

Usage:  python3 gen_camera_oui.py oui.csv > ../src/engines/camera_oui.h
Source: https://standards-oui.ieee.org/oui/oui.csv
"""
import csv, re, sys

# Camera manufacturers. Matched against the IEEE "Organization Name" with a
# word-boundary regex so e.g. "Ring LLC" does not match "RingBell Co".
VENDORS = {
    'Ring LLC': 'Ring',
    'Wyze Labs': 'Wyze',
    'Nest Labs': 'Nest',
    'Arlo Technolog': 'Arlo',
    'Hikvision': 'Hikvision',
    'Dahua': 'Dahua',
    'Reolink': 'Reolink',
    'Amcrest': 'Amcrest',
    'Lorex': 'Lorex',
    'Swann': 'Swann',
    'Axis Communicat': 'Axis',
    'VIVOTEK': 'Vivotek',
    'GeoVision': 'GeoVision',
    'Foscam': 'Foscam',
    'eufy': 'eufy',
    'Anker Innovations': 'eufy',
    # Enterprise / municipal video surveillance.
    'Verkada': 'Verkada',
    'Avigilon': 'Avigilon',
    # Municipal / parking ALPR (AutoVu). 'Genetec Inc.' is matched in full
    # on purpose: 'GENETEC Corporation' is an unrelated Japanese firm, and
    # 'Netgenetech' merely contains the substring.
    'Genetec Inc.': 'Genetec',
}


def vendor_of(org):
    for pat, name in VENDORS.items():
        if re.search(r'\b' + re.escape(pat), org, re.I):
            return name
    return None


def main(path):
    rows = []
    with open(path, newline='', encoding='utf-8', errors='replace') as fh:
        for rec in csv.DictReader(fh):
            if rec.get('Registry') != 'MA-L':
                continue
            asn = (rec.get('Assignment') or '').strip().upper()
            if len(asn) != 6:
                continue
            name = vendor_of((rec.get('Organization Name') or '').strip())
            if name:
                rows.append((asn, name))

    seen, uniq = set(), []
    for asn, name in sorted(rows):
        if asn not in seen:
            seen.add(asn)
            uniq.append((asn, name))
    # Bucket lookup indexes with uint8_t, same as the Flock table.
    assert len(uniq) < 256, 'table exceeds uint8_t bucket index'

    out = sys.stdout.write
    out('// SPDX-License-Identifier: MIT\n')
    out('// Generated by tools/gen_camera_oui.py from the IEEE MA-L registry.\n')
    out('// Do not edit by hand; re-run the generator to refresh.\n')
    out('// %d camera-vendor OUIs.\n' % len(uniq))
    out('#ifndef CAMERA_OUI_H\n#define CAMERA_OUI_H\n\n')
    out('#include <stdint.h>\n#include <string.h>\n\n')
    out('struct CameraOui { uint8_t b[3]; uint8_t ext; const char* vendor; };\n\n')
    out('// Frames weaker than this are ignored (matches the Flock engine).\n')
    out('#define CAMERA_RSSI_MIN (-95)\n\n')
    out('extern volatile bool g_cameraExtendedOui;\n\n')
    out('static const CameraOui CAMERA_OUI_TABLE[] = {\n')
    for asn, name in uniq:
        out('    {{0x%s,0x%s,0x%s}, 0, "%s"},\n' % (asn[0:2].lower(), asn[2:4].lower(),
                                                    asn[4:6].lower(), name))
    out('};\n')
    out('static const int CAMERA_OUI_COUNT =\n'
        '    sizeof(CAMERA_OUI_TABLE) / sizeof(CAMERA_OUI_TABLE[0]);\n\n')
    out('''struct CameraOuiBucket { uint8_t start; uint8_t count; };
static CameraOuiBucket cameraOuiBuckets[256];
static bool cameraOuiBucketsReady = false;

// Index the table by first OUI byte so a lookup only walks one bucket.
static inline void cameraOuiInitBuckets() {
    if (cameraOuiBucketsReady) return;
    memset(cameraOuiBuckets, 0, sizeof(cameraOuiBuckets));
    for (int i = 0; i < CAMERA_OUI_COUNT; i++) {
        uint8_t b = CAMERA_OUI_TABLE[i].b[0];
        if (cameraOuiBuckets[b].count == 0) cameraOuiBuckets[b].start = (uint8_t)i;
        cameraOuiBuckets[b].count++;
    }
    cameraOuiBucketsReady = true;
}

// Returns the vendor name, or nullptr when the OUI is not a known camera vendor.
static inline const char* cameraMatchOui(const uint8_t* mac) {
    if (mac[0] & 0x02) return nullptr;          // locally administered / random
    if (!cameraOuiBucketsReady) cameraOuiInitBuckets();
    const CameraOuiBucket& k = cameraOuiBuckets[mac[0]];
    for (int i = k.start; i < k.start + k.count; i++) {
        if (mac[1] == CAMERA_OUI_TABLE[i].b[1] && mac[2] == CAMERA_OUI_TABLE[i].b[2]) {
            if (CAMERA_OUI_TABLE[i].ext && !g_cameraExtendedOui) continue;
            return CAMERA_OUI_TABLE[i].vendor;
        }
    }
    return nullptr;
}

// ISR-safe variant: never builds the buckets, just misses until they are ready.
static inline const char* IRAM_ATTR cameraMatchOuiISR(const uint8_t* mac) {
    if (mac[0] & 0x02) return nullptr;
    if (!cameraOuiBucketsReady) return nullptr;
    const CameraOuiBucket& k = cameraOuiBuckets[mac[0]];
    for (int i = k.start; i < k.start + k.count; i++) {
        if (mac[1] == CAMERA_OUI_TABLE[i].b[1] && mac[2] == CAMERA_OUI_TABLE[i].b[2]) {
            if (CAMERA_OUI_TABLE[i].ext && !g_cameraExtendedOui) continue;
            return CAMERA_OUI_TABLE[i].vendor;
        }
    }
    return nullptr;
}

#endif // CAMERA_OUI_H
''')


if __name__ == '__main__':
    main(sys.argv[1])
