"""Generate drone_oui.h from the IEEE MA-L registry.

Drone makers' OUIs, for Sky Spy's backstop when a drone is not broadcasting
Remote ID. Matched against the IEEE "Organization Name" exactly as registered,
and kept narrow: DJI also registers OUIs for gimbals (SZ DJI Ronin), handheld
cameras (DJI Osmo) and other subsidiaries, and Parrot's OUIs largely cover car
kits and headphones, so those are left out rather than flag non-aircraft.

Usage:  python3 gen_drone_oui.py oui.csv > ../src/engines/drone_oui.h
Source: https://standards-oui.ieee.org/oui/oui.csv
"""
import csv, re, sys

VENDORS = [
    (r'^SZ DJI TECHNOLOGY CO', 'DJI'),
    (r'^Skydio Inc', 'Skydio'),
]


def main(path):
    rows = []
    with open(path, newline='', encoding='utf-8', errors='replace') as fh:
        for rec in csv.DictReader(fh):
            if rec.get('Registry') != 'MA-L':
                continue
            asn = (rec.get('Assignment') or '').strip().upper()
            org = (rec.get('Organization Name') or '').strip()
            if len(asn) != 6:
                continue
            for pat, name in VENDORS:
                if re.search(pat, org, re.I):
                    rows.append((asn, name))
                    break
    rows = sorted(set(rows))
    out = sys.stdout.write
    out('// SPDX-License-Identifier: MIT\n')
    out('// Generated by tools/gen_drone_oui.py from the IEEE MA-L registry.\n')
    out('// Do not edit by hand; re-run the generator to refresh.\n')
    out('// %d drone-vendor OUIs.\n' % len(rows))
    out('#pragma once\n#include <stdint.h>\n\n')
    out('struct DroneVendorOui { uint8_t b[3]; const char* vendor; };\n')
    out('static const DroneVendorOui DRONE_VENDOR_OUIS[] = {\n')
    for asn, name in rows:
        b = [int(asn[i:i + 2], 16) for i in (0, 2, 4)]
        out('    {{0x%02x,0x%02x,0x%02x}, "%s"},\n' % (b[0], b[1], b[2], name))
    out('};\n')
    out('static const int DRONE_VENDOR_OUI_COUNT =\n'
        '    sizeof(DRONE_VENDOR_OUIS) / sizeof(DRONE_VENDOR_OUIS[0]);\n')


if __name__ == '__main__':
    main(sys.argv[1])
