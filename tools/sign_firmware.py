"""Sign firmware for over-the-air updates (format: src/ota_sig_format.h).

The private key lives only on the release machine, never in the repository or
CI. The board carries the public key, generated into src/ota_pubkey.h.

  sign_firmware.py keygen  --key KEY.pem     new key + src/ota_pubkey.h
  sign_firmware.py pubkey  --key KEY.pem     rewrite src/ota_pubkey.h
  sign_firmware.py sign    --key KEY.pem --target node-esp32s3 IN.bin OUT.bin
  sign_firmware.py verify  --target node-esp32s3 FILE.bin   (uses ota_pubkey.h)

Needs the `cryptography` package.
"""
import argparse, hashlib, os, re, sys
from pathlib import Path

try:
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.hazmat.primitives.asymmetric.utils import (
        decode_dss_signature, encode_dss_signature)
    from cryptography.exceptions import InvalidSignature
except ImportError:
    sys.exit('needs the cryptography package: pip install cryptography')

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / 'src' / 'ota_pubkey.h'
DOMAIN = b'OUI-SNITCH-OTA1\n'
MAGIC = b'OSNSIG01'
TRAILER_LEN = len(MAGIC) + 4 + 64
TARGET_RE = re.compile(r'^(node|manager)-esp32(s3|c3|c5|c6)?$')


def raw_pub(pub):
    return pub.public_bytes(serialization.Encoding.X962,
                            serialization.PublicFormat.UncompressedPoint)


def key_id(raw):
    return hashlib.sha256(raw).digest()[:4]


def preimage(target, image):
    return DOMAIN + target.encode() + b'\n' + image


def load_key(path):
    with open(path, 'rb') as fh:
        key = serialization.load_pem_private_key(fh.read(), password=None)
    if not isinstance(key, ec.EllipticCurvePrivateKey) or key.curve.name != 'secp256r1':
        sys.exit('%s is not a P-256 key' % path)
    return key


def header_pub():
    text = HEADER.read_text()
    body = text[text.index('OTA_PUBKEY[65]'):]
    raw = bytes(int(b, 16) for b in re.findall(r'0x([0-9a-f]{2})', body)[:65])
    return ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), raw)


def write_header(pub):
    raw = raw_pub(pub)
    rows = ',\n'.join('    ' + ', '.join('0x%02x' % b for b in raw[i:i + 13])
                      for i in range(0, 65, 13))
    HEADER.write_text(
        '// SPDX-License-Identifier: MIT\n'
        '// Generated by tools/sign_firmware.py. The public half of the release\n'
        '// signing key; the board accepts updates signed by its private half.\n'
        '#pragma once\n#include <stdint.h>\n\n'
        'static const uint8_t OTA_PUBKEY_ID[4] = {%s};\n\n'
        'static const uint8_t OTA_PUBKEY[65] = {\n%s\n};\n'
        % (', '.join('0x%02x' % b for b in key_id(raw)), rows))
    print('wrote %s (key id %s)' % (HEADER.relative_to(ROOT), key_id(raw).hex()))


def check_target(t):
    if not TARGET_RE.match(t):
        sys.exit('target %r is not role-chip, e.g. node-esp32s3' % t)


def verify_bytes(pub, target, data):
    """Returns None if `data` is a correctly signed image, else the reason."""
    if len(data) <= TRAILER_LEN:
        return 'too short'
    image, trailer = data[:-TRAILER_LEN], data[-TRAILER_LEN:]
    if trailer[:len(MAGIC)] != MAGIC:
        return 'not signed'
    if trailer[8:12] != key_id(raw_pub(pub)):
        return 'signed with key %s, expected %s' % (trailer[8:12].hex(), key_id(raw_pub(pub)).hex())
    rs = trailer[12:]
    der = encode_dss_signature(int.from_bytes(rs[:32], 'big'), int.from_bytes(rs[32:], 'big'))
    try:
        pub.verify(der, preimage(target, image), ec.ECDSA(hashes.SHA256()))
    except InvalidSignature:
        return 'bad signature (tampered, or signed for another target)'
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('cmd', choices=['keygen', 'pubkey', 'sign', 'verify'])
    ap.add_argument('--key')
    ap.add_argument('--target')
    ap.add_argument('files', nargs='*')
    a = ap.parse_args()

    if a.cmd == 'keygen':
        if not a.key:
            sys.exit('--key is required')
        if os.path.exists(a.key):
            sys.exit('%s exists; refusing to replace a signing key' % a.key)
        key = ec.generate_private_key(ec.SECP256R1())
        pem = key.private_bytes(serialization.Encoding.PEM,
                                serialization.PrivateFormat.PKCS8,
                                serialization.NoEncryption())
        fd = os.open(a.key, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, 'wb') as fh:
            fh.write(pem)
        print('wrote %s; back it up off this machine' % a.key)
        write_header(key.public_key())
    elif a.cmd == 'pubkey':
        write_header(load_key(a.key).public_key())
    elif a.cmd == 'sign':
        if not a.key or len(a.files) != 2:
            sys.exit('usage: sign --key KEY --target TARGET IN.bin OUT.bin')
        check_target(a.target)
        key = load_key(a.key)
        image = Path(a.files[0]).read_bytes()
        if not image or image[0] != 0xE9:
            sys.exit('%s is not an ESP32 app image' % a.files[0])
        if len(image) > TRAILER_LEN and image[-TRAILER_LEN:][:len(MAGIC)] == MAGIC:
            sys.exit('%s is already signed' % a.files[0])
        if raw_pub(key.public_key()) != raw_pub(header_pub()):
            sys.exit('this key does not match src/ota_pubkey.h; boards would refuse the image')
        r, s = decode_dss_signature(key.sign(preimage(a.target, image), ec.ECDSA(hashes.SHA256())))
        out = image + MAGIC + key_id(raw_pub(key.public_key())) + r.to_bytes(32, 'big') + s.to_bytes(32, 'big')
        err = verify_bytes(header_pub(), a.target, out)
        if err:
            sys.exit('self-check failed: ' + err)
        Path(a.files[1]).write_bytes(out)
        print('signed %s for %s -> %s' % (a.files[0], a.target, a.files[1]))
    else:
        if len(a.files) != 1:
            sys.exit('usage: verify --target TARGET FILE.bin')
        check_target(a.target)
        err = verify_bytes(header_pub(), a.target, Path(a.files[0]).read_bytes())
        print('%s: %s' % (a.files[0], err or 'good signature for ' + a.target))
        sys.exit(1 if err else 0)


if __name__ == '__main__':
    main()
